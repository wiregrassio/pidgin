def write_nest_claude_md(repo_root: str, *, force: bool = False) -> str:
    """Write .pidgin/CLAUDE.md at the git root above repo_root.

    Resolves the git root by walking up from repo_root. Falls back to
    repo_root when no .git ancestor exists.
    Skips writing if the file already exists and force=False.
    Returns the path whether written or not.
    """
    resolved = find_project_root(repo_root) or repo_root
    path = os.path.join(resolved, ".pidgin", "CLAUDE.md")
    if os.path.exists(path) and not force:
        return path
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(NEST_CLAUDE_MD_TEMPLATE)
    return path


def _repo_nest_client(repo_root: str) -> chromadb.api.ClientAPI:
    """Open or create a persistent ChromaDB client at <repo_root>/.pidgin/nest/."""
    path = nest_path(repo_root)
    os.makedirs(path, exist_ok=True)
    settings = chromadb.Settings(
        anonymized_telemetry=False,
        allow_reset=True,
    )
    return chromadb.PersistentClient(path=path, settings=settings)


def _repo_descriptions_col(repo_root: str) -> chromadb.Collection:
    """Get-or-create the 'function_descriptions' collection in the per-repo nest."""
    client = _repo_nest_client(repo_root)
    return client.get_or_create_collection(
        name=_COLLECTION_FUNC_DESCRIPTIONS,
        embedding_function=None,
        metadata={"hnsw:space": "cosine"},
    )


def query(repo_root: str, text: str, n_results: int = 5) -> list[dict]:
    """Embed text and search the local nest at repo_root/.pidgin/nest/.

    Returns a list of hit dicts with keys: function_name, description, similarity, file.
    Returns [] if the nest does not exist or contains no results.
    """
    nest_dir = nest_path(repo_root)
    if not os.path.exists(nest_dir):
        return []

    try:
        col = _repo_descriptions_col(repo_root)
    except Exception:
        return []

    try:
        vectors = asyncio.run(api.embed_for_store(text))
    except RuntimeError:
        import concurrent.futures
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as ex:
            vectors = ex.submit(asyncio.run, api.embed_for_store(text)).result()

    query_vec = vectors[0]

    try:
        result = col.query(
            query_embeddings=[query_vec],
            n_results=n_results,
            include=["metadatas", "distances"],
        )
    except Exception:
        return []

    if not result or not result.get("ids") or not result["ids"][0]:
        return []

    ids = result["ids"][0]
    distances = (result.get("distances") or [[None] * len(ids)])[0]
    metadatas = (result.get("metadatas") or [[{}] * len(ids)])[0]

    hits = []
    for i in range(len(ids)):
        meta = metadatas[i] or {}
        dist = distances[i]
        similarity = (1.0 - dist) if dist is not None else 0.0
        hits.append({
            "function_name": meta.get("name", ids[i]),
            "description": meta.get("description", ""),
            "similarity": similarity,
            "file": meta.get("file", ""),
        })
    return hits


