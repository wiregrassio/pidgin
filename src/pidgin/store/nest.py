def _resolve_nest_dir(anchor: str | None) -> str:
    """Resolve the canonical .pidgin/nest/ location for an anchor path.

    Walks up to .git. If no .git is found, falls back to anchor with a
    warning printed to stderr.
    """
    anchor = anchor or os.getcwd()
    root = find_project_root(anchor)
    if root is None:
        print(
            f"[nest] WARNING: no .git found above {anchor}; "
            f"using {anchor} as nest anchor.",
            file=sys.stderr,
        )
        root = anchor
    return os.path.join(root, ".pidgin", "nest")


def nest_path(repo_root: str) -> str:
    """Return the per-repo ChromaDB store path rooted at the git root.

    Walks up from repo_root to find the .git boundary. Falls back to
    repo_root itself if no .git ancestor exists (with a stderr warning).
    """
    return _resolve_nest_dir(repo_root)


def ensure_nest(repo_root: str) -> str:
    """Create <git_root>/.pidgin/nest/ if it does not exist. Return the path.

    git_root is resolved by walking up from repo_root to the nearest .git.
    Falls back to repo_root when no .git ancestor exists.
    """
    path = _resolve_nest_dir(repo_root)
    os.makedirs(path, exist_ok=True)
    return path


