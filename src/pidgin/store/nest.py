def store_path() -> Path:
    """Return the canonical ChromaDB persistent store directory.

    Provenance: sections_chroma.store_path (v0.1). Canonical name retained
    for backward compat; vectors.py called this nest_path().
    """
    repo_root = Path(__file__).resolve().parent.parent.parent.parent
    return repo_root / "local" / "store" / "nest"


# _global_nest_path() — original alias retained internally.
def _global_nest_path() -> Path:
    """Return the canonical local/store/nest/ persistence directory (alias of store_path)."""
    return store_path()


