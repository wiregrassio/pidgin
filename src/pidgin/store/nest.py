def query_by_path(nest_path: str, text: str, n_results: int = 5) -> list[dict]:
    """Embed text and search the nest at the given direct nest_path (not repo_root).

    Unlike query(), this function takes the absolute path to the .pidgin/nest/
    directory itself, enabling callers to search nests discovered via the registry
    without having to reconstruct a repo_root.

    Returns a list of hit dicts with keys: function_name, description, similarity, file.
    Returns [] if the nest does not exist, is empty, or fails to open (e.g. corrupt
    sqlite3 file). ChromaDB open errors are caught and logged as warnings rather than
    raised, so a multi-nest search can continue past failed nests.
    """
    if not os.path.isdir(nest_path):
        return []

    try:
        settings = chromadb.Settings(
            anonymized_telemetry=False,
            allow_reset=True,
        )
        client = chromadb.PersistentClient(path=nest_path, settings=settings)
        col = client.get_or_create_collection(
            name=_COLLECTION_FUNC_DESCRIPTIONS,
            embedding_function=None,
            metadata={"hnsw:space": "cosine"},
        )
    except Exception as exc:
        import warnings
        warnings.warn(f"[query_by_path] Could not open ChromaDB at {nest_path}: {exc}")
        return []

    try:
        vectors = asyncio.run(api.embed_for_store(text))
    except RuntimeError:
        import concurrent.futures
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as ex:
            vectors = ex.submit(asyncio.run, api.embed_for_store(text)).result()

    query_vec = vectors[0]

    try:
        result = col.query(
            query_embeddings=[query_vec],
            n_results=n_results,
            include=["metadatas", "distances"],
        )
    except Exception:
        return []

    if not result or not result.get("ids") or not result["ids"][0]:
        return []

    ids = result["ids"][0]
    distances = (result.get("distances") or [[None] * len(ids)])[0]
    metadatas = (result.get("metadatas") or [[{}] * len(ids)])[0]

    hits = []
    for i in range(len(ids)):
        meta = metadatas[i] or {}
        dist = distances[i]
        similarity = (1.0 - dist) if dist is not None else 0.0
        hits.append({
            "function_name": meta.get("name", ids[i]),
            "description": meta.get("description", ""),
            "similarity": similarity,
            "file": meta.get("file", ""),
        })
    return hits


def upsert_function_descriptions(
    repo_root: str,
    results: list,
    functions: list[dict] | None = None,
    *,
    file_meta: dict | None = None,
) -> None:
    """Upsert FunctionMldResult list into the per-repo <repo_root>/.pidgin/nest/ ChromaDB.

    Provenance: v0.1 section_put in tools/store/sections_chroma.py.
    M12: Fixed to write to per-repo .pidgin/nest/ (not global local/store/nest/).
    M9-patch: Added optional `functions` parameter (parallel list of function dicts
    from extract_public_functions). When provided, the "file" metadata field is set
    to the per-function source file path (fn["file"]). When absent, falls back to
    str(repo_root) for backward compatibility.
    M12-patch: Added optional `file_meta` parameter ({rel_path: FileMeta} lookup built
    by index.py). When provided, the per-function FunctionSignature is serialised to
    JSON and stored as signature_json; decorator names are stored as decorators_str.

    For each FunctionMldResult with at least one candidate description, picks
    the candidate at index 0 from the dominant cluster (first candidate is
    representative of the converged cluster when converged=True, or the best
    available when not converged). Upserts into the per-repo function_descriptions
    collection keyed by function_id(repo_root, result.name, 0).

    When no candidates exist for a result, the result is skipped silently.
    """
    from dataclasses import asdict
    import json as _json
    from pathlib import Path as _Path

    col = _repo_descriptions_col(repo_root)
    git_ref = _vec_git_ref()

    for i, result in enumerate(results):
        if not result.candidates:
            continue
        description = result.candidates[0]
        fid = function_id(str(repo_root), result.name, 0)

        # Resolve per-function file path from the parallel functions list when provided.
        fn = functions[i] if (functions is not None and i < len(functions)) else {}
        if fn:
            file_path = fn.get("file", str(repo_root))
        else:
            file_path = str(repo_root)

        # M12-patch: look up FunctionSignature from the file_meta dict.
        sig_json = ""
        dec_str = ""
        if file_meta and fn:
            rel = fn.get("file", "")
            fm = file_meta.get(rel)
            if fm is None and rel:
                # try resolving relative to repo_root
                try:
                    rel_key = str(_Path(rel).relative_to(repo_root))
                    fm = file_meta.get(rel_key)
                except Exception:
                    pass
            if fm is not None:
                func_name = fn.get("name", result.name)
                sig = next(
                    (s for s in fm.functions if s.name == func_name),
                    None,
                )
                if sig is not None:
                    sig_json = _json.dumps(asdict(sig))
                    dec_str = ",".join(sig.decorators)

        # Embed the description for the per-repo store.
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = None

        if loop is not None:
            import concurrent.futures
            with concurrent.futures.ThreadPoolExecutor(max_workers=1) as ex:
                vectors = ex.submit(asyncio.run, api.embed_for_store(description)).result()
        else:
            vectors = asyncio.run(api.embed_for_store(description))
        desc_vec = vectors[0]

        # M13: pull source_hash from the parallel function dict if present.
        # Empty string means "no hash known" — diff_against_nest will treat
        # any pre-M13 record as UPDATED on the next index pass.
        src_hash = ""
        if fn:
            src_hash = fn.get("source_hash", "") or ""

        metadata = {
            "file": file_path,
            "name": result.name,
            "description": description,
            "converged": bool(result.converged),
            "git_ref": git_ref,
            "line_start": 0,
            "line_end": 0,
            "language": "python",
            "module": "",
            "visibility": "public",
            "natural_length": len(description),
            "signature_json": sig_json,
            "decorators_str": dec_str,
            "source_hash": src_hash,
        }

        col.upsert(
            ids=[fid],
            documents=[description],
            embeddings=[desc_vec],
            metadatas=[metadata],
        )


