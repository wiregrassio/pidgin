def _sec_git_ref() -> str | None:
    """Return short git HEAD ref, or None (sections-store version, may return None)."""
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip() or None
    except Exception:
        return None


def _vec_git_ref() -> str:
    """Return short git HEAD ref, or '' (vectors version, never returns None)."""
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
        return out or ""
    except Exception:
        return ""


def _git_user() -> str:
    """Return git config user.name, or $USER, or 'unknown'."""
    try:
        name = subprocess.check_output(
            ["git", "config", "user.name"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
        return name or os.environ.get("USER", "unknown")
    except Exception:
        return os.environ.get("USER", "unknown")


def _now_utc_iso() -> str:
    """Return ISO-8601 UTC timestamp, second precision, e.g. 2026-04-25T12:34:56Z."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# ---------------------------------------------------------------------------
# Content hash and doc-id helpers (sections store)
# ---------------------------------------------------------------------------

def _hash(content: str) -> str:
    """Return first 8 hex chars of sha256(content)."""
    return hashlib.sha256(content.encode()).hexdigest()[:8]


def _doc_id(file: str, tag: str) -> str:
    """Compose the ChromaDB document ID as f'{file}:{tag}'."""
    return f"{file}:{tag}"


# ---------------------------------------------------------------------------
# ID generation (vector store)
# ---------------------------------------------------------------------------

def function_id(file: str, name: str, line_start: int) -> str:
    """Stable 16-char ID = sha256(f"{file}:{name}:{line_start}")[:16].

    Keyed on line_start so that growing a function body without moving its
    starting line produces the same ID — the upsert overwrites the prior row
    instead of leaking a duplicate.
    """
    key = f"{file}:{name}:{line_start}"
    return hashlib.sha256(key.encode()).hexdigest()[:16]


