class FunctionRecord:
    """Lightweight record yielded by iter_records.

    Fields used by pidgin egg:
      file_path      — absolute path to the source file.
      symbol_name    — function or class name.
      symbol_kind    — "function" | "class" | etc. (from metadata.language field,
                       defaulting to "function" when absent).
      mld_description — the MLD description string (may be empty).
      file_summary   — one-paragraph file-level summary from the sections store,
                       or None when no summary has been generated yet.
      signature      — dict from FunctionSignature.asdict(), or None when the nest
                       was written before M12 (older records lack this field).
      decorators     — list of decorator strings, or [] when absent.
      source_hash    — sha256 hex of the normalised function source (M13).
                       Empty string for records written before M13 — those
                       count as UPDATED on first re-index, forcing one re-MLD.
      record_id      — the ChromaDB document ID this record came from (M13).
                       Used by prune() to delete by id without re-deriving it.
    """

    __slots__ = (
        "file_path", "symbol_name", "symbol_kind", "mld_description",
        "file_summary", "signature", "decorators", "source_hash", "record_id",
    )

    def __init__(
        self,
        file_path: str,
        symbol_name: str,
        symbol_kind: str,
        mld_description: str,
        file_summary: str | None,
        signature: "dict | None" = None,
        decorators: "list[str] | None" = None,
        source_hash: str = "",
        record_id: str = "",
    ) -> None:
        self.file_path = file_path
        self.symbol_name = symbol_name
        self.symbol_kind = symbol_kind
        self.mld_description = mld_description
        self.file_summary = file_summary
        self.signature = signature
        self.decorators: list[str] = decorators if decorators is not None else []
        self.source_hash = source_hash
        self.record_id = record_id


def iter_records(repo_root: str):
    """Yield FunctionRecord objects for every entry in <repo_root>/.pidgin/nest/.

    Reads function_descriptions collection from the per-repo ChromaDB.
    For each unique file_path found, fetches the file-level summary from
    the global sections store (section_get_chroma(file_path, "file_summary")).

    Yields nothing (empty iterator) when the nest does not exist or is empty.
    Callers (e.g. egg) check for emptiness and exit 1 accordingly.
    """
    nest_dir = nest_path(repo_root)
    if not os.path.isdir(nest_dir):
        return

    try:
        col = _repo_descriptions_col(repo_root)
        result = col.get(include=["metadatas", "documents"])
    except Exception:
        return

    if not result or not result.get("ids"):
        return

    ids = result["ids"]
    metadatas = result.get("metadatas") or [{}] * len(ids)
    documents = result.get("documents") or [""] * len(ids)

    # Pre-fetch file summaries for all unique files in one pass.
    file_summary_cache: dict[str, str | None] = {}
    for meta in metadatas:
        fp = (meta or {}).get("file", "")
        if fp and fp not in file_summary_cache:
            row = section_get_chroma(fp, "file_summary")
            file_summary_cache[fp] = row[0] if row else None

    for i, fid in enumerate(ids):
        import json as _json
        meta = metadatas[i] or {}
        fp = meta.get("file", "")
        name = meta.get("name", fid)
        # symbol_kind: nest metadata does not carry a kind field today; default
        # to "function".  When M12 adds class support this will be populated.
        kind = meta.get("symbol_kind", "function")
        desc = documents[i] or meta.get("description", "")
        summary = file_summary_cache.get(fp)
        # M12: deserialise signature_json back to dict; empty string → None.
        sig_raw = meta.get("signature_json", "") or ""
        try:
            signature = _json.loads(sig_raw) if sig_raw else None
        except Exception:
            signature = None
        # M12: deserialise comma-joined decorators_str back to list.
        dec_raw = meta.get("decorators_str", "") or ""
        decorators = [d for d in dec_raw.split(",") if d] if dec_raw else []
        # M13: surface source_hash and record id for the idempotency diff.
        source_hash = meta.get("source_hash", "") or ""
        yield FunctionRecord(
            file_path=fp,
            symbol_name=name,
            symbol_kind=kind,
            mld_description=desc,
            file_summary=summary,
            signature=signature,
            decorators=decorators,
            source_hash=source_hash,
            record_id=fid,
        )


# ---------------------------------------------------------------------------
# Public API — index idempotency (M13)
# ---------------------------------------------------------------------------
#
# The index verb builds a parallel list of (file, function_name, source_hash)
# from the source tree, then asks diff_against_nest to classify each entry
# against the existing nest:
#
#   UNCHANGED  — same identity key, same source_hash. No MLD; no embed; no upsert.
#   UPDATED    — same identity key, different source_hash (or empty source_hash
#                in the existing record, i.e. pre-M13). Re-MLD and re-upsert.
#   NEW        — identity key not in the nest. MLD and upsert.
#   DELETED    — record in nest but no matching identity key in the source tree.
#                Hard-deleted via prune().
#
# Identity key: (file_rel_path, function_name).
#
# Concurrency assumption: index runs single-process. No file-level locking on
# .pidgin/. A future parallel-index implementation must add locking before
# reading the existing nest contents.

@dataclass
class IdempotencyDiff:
    """Classification of source functions against the nest.

    Fields:
      unchanged — list[FunctionRecord]
        Records whose source_hash matches the source tree. Skipped entirely.
      updated   — list[tuple[FunctionRecord, dict]]
        Pairs of (existing record, new function dict from extract_public_functions).
        Re-MLD using the new dict; the old record is overwritten on upsert.
      new       — list[dict]
        Function dicts present in the source tree but not in the nest. MLD them.
      deleted   — list[FunctionRecord]
        Records present in the nest but absent from the source tree. Pruned.
    """
    unchanged: list = field(default_factory=list)
    updated:   list = field(default_factory=list)
    new:       list = field(default_factory=list)
    deleted:   list = field(default_factory=list)


def _identity_key(file_rel_path: str, name: str) -> tuple:
    """Return the canonical identity key used by the M13 idempotency diff.

    Tuple of (file_rel_path, name). file_rel_path is whatever string the
    caller threads through — typically a path relative to repo_root. The
    diff treats the key as opaque: equality comparison only.
    """
    return (file_rel_path, name)


def diff_against_nest(
    repo_root: str,
    new_functions: list,
) -> IdempotencyDiff:
    """Compare the source-tree function list against the existing nest.

    Args:
      repo_root: absolute path to the project root. Used to open the
        per-repo nest at <repo_root>/.pidgin/nest/. If the nest does not
        exist (first-ever index), every input function is classified NEW.
      new_functions: iterable of (file_rel_path, fn_dict) pairs. Each
        fn_dict must contain at least 'name' and 'source_hash' keys (the
        index verb populates source_hash via parser.function_dict_hash).

    Returns:
      IdempotencyDiff. Identity key is (file_rel_path, fn['name']).

    Pre-M13 records (those without a source_hash field, or with an empty
    string) are reported as UPDATED — their first re-index re-MLDs once
    and writes the hash, after which they remain UNCHANGED until the
    source actually changes.
    """
    # Build a lookup of existing records keyed by (file, name).
    nest_records_by_key: dict = {}
    for rec in iter_records(repo_root):
        key = _identity_key(rec.file_path, rec.symbol_name)
        nest_records_by_key[key] = rec

    diff = IdempotencyDiff()
    seen_keys: set = set()

    for file_rel_path, fn in new_functions:
        name = fn.get("name", "")
        key = _identity_key(file_rel_path, name)
        seen_keys.add(key)

        existing = nest_records_by_key.get(key)
        new_hash = fn.get("source_hash", "") or ""

        if existing is None:
            diff.new.append(fn)
            continue

        # Pre-M13 records have an empty source_hash. Treat as UPDATED so the
        # first index pass after the upgrade re-MLDs once and populates the
        # hash field. Subsequent passes will resolve to UNCHANGED.
        if not existing.source_hash or existing.source_hash != new_hash:
            diff.updated.append((existing, fn))
        else:
            diff.unchanged.append(existing)

    # Anything in the nest that we did not visit is DELETED.
    for key, rec in nest_records_by_key.items():
        if key not in seen_keys:
            diff.deleted.append(rec)

    return diff


def prune(repo_root: str, record_ids: list) -> int:
    """Hard-delete records from the per-repo nest by ChromaDB document id.

    Used by the index verb to remove DELETED records (functions that were
    in the nest but are no longer in the source tree). Hard-delete chosen
    over soft-tombstone because no caller depends on tombstoned function
    records — egg, query, and depends all skip records they cannot
    correlate to a live source file.

    Returns the number of ids requested for deletion (Chroma silently
    ignores ids that do not exist, so this is a best-effort count).
    Returns 0 immediately if record_ids is empty.
    """
    if not record_ids:
        return 0
    try:
        col = _repo_descriptions_col(repo_root)
        col.delete(ids=list(record_ids))
    except Exception as exc:
        print(
            f"[nest] WARNING: prune failed for {len(record_ids)} ids: {exc}",
            file=sys.stderr,
        )
        return 0
    return len(record_ids)
