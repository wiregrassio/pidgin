async def upsert_function(
    file: str,
    name: str,
    line_start: int,
    line_end: int,
    body: str,
    *,
    description: str | None = None,
    language: str,
    module: str,
    visibility: str,
    natural_length: int,
    git_ref: str | None = None,
    signature_json: str | None = None,
    decorators_str: str | None = None,
) -> str:
    """Embed body (and optionally description) and upsert into ChromaDB.

    When ``description`` is provided (not None):
      - One batched embed_for_store([body, description]) call produces both
        vectors in a single round-trip.
      - Body vector → function_bodies. Description vector → function_descriptions.
      - Identical id and metadata in both collections for cross-lookup.

    When ``description`` is None (no MLD exists yet):
      - Only the body string is embedded via embed_for_store(body).
      - Upserted into function_bodies only.
      - function_descriptions is NOT written — querying it returns zero results
        until /digest runs (fail-safe, not stale).
      - Metadata on the body side records description="" and natural_length=0 as
        sentinels (Chroma rejects None values).

    Returns the function_id either way.
    """
    fid = function_id(file, name, line_start)
    resolved_git_ref = _vec_git_ref() if git_ref is None else git_ref
    bodies, descs_col = _vec_collections()

    if description is None:
        # Body-only path.
        vectors = await api.embed_for_store(body)
        body_vec = vectors[0]

        metadata = _build_function_metadata(
            file=file,
            name=name,
            line_start=line_start,
            line_end=line_end,
            description="",
            language=language,
            module=module,
            visibility=visibility,
            natural_length=0,
            git_ref=resolved_git_ref,
            signature_json=signature_json,
            decorators_str=decorators_str,
        )

        bodies.upsert(
            ids=[fid],
            documents=[body],
            embeddings=[body_vec],
            metadatas=[metadata],
        )
        # function_descriptions intentionally skipped — see docstring.
    else:
        # Dual-write path: two strings in, two vectors out.
        vectors = await api.embed_for_store([body, description])
        body_vec, desc_vec = vectors[0], vectors[1]

        metadata = _build_function_metadata(
            file=file,
            name=name,
            line_start=line_start,
            line_end=line_end,
            description=description,
            language=language,
            module=module,
            visibility=visibility,
            natural_length=natural_length,
            git_ref=resolved_git_ref,
            signature_json=signature_json,
            decorators_str=decorators_str,
        )

        bodies.upsert(
            ids=[fid],
            documents=[body],
            embeddings=[body_vec],
            metadatas=[metadata],
        )
        descs_col.upsert(
            ids=[fid],
            documents=[description],
            embeddings=[desc_vec],
            metadatas=[metadata],
        )

    return fid


