def section_put_chroma(
    file: str,
    tag: str,
    content: str,
    *,
    model: str | None = None,
    doc_type: str = "function_description",
    confidence: float | None = None,
    converged: bool | None = None,
) -> bool:
    """Write a section to ChromaDB with hash idempotency.

    - Compute new_hash = _hash(content).
    - Read existing document by id = _doc_id(file, tag); if present and its
      metadata['source_hash'] == new_hash, return False (no write).
    - Otherwise embed content via api.embed_for_store and upsert with metadata:
      {file, tag, version, updated, by, model, source_hash, git_ref,
       doc_type, confidence, converged}
      where version = old_version + 1 if a prior row exists, else 1.
    - confidence: stored as float; -1.0 when None (-1.0 is an out-of-band
      sentinel since real confidences are clamped to [0.0, 1.0]).
    - converged: stored as bool; False when None.
    - Return True iff a write happened.
    """
    doc_id = _doc_id(file, tag)
    new_hash = _hash(content)

    collection = _descriptions_col()

    # Check for existing document.
    existing = collection.get(ids=[doc_id], include=["metadatas"])
    existing_meta = None
    if existing and existing["ids"]:
        existing_meta = existing["metadatas"][0]
        if existing_meta.get("source_hash") == new_hash:
            return False
        new_version = int(existing_meta.get("version", 0)) + 1
    else:
        new_version = 1

    # Embed content — handle running event loop (e.g. called from an async skill).
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None

    if loop is not None:
        import concurrent.futures
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as ex:
            vectors = ex.submit(asyncio.run, api.embed_for_store(content)).result()
    else:
        vectors = asyncio.run(api.embed_for_store(content))
    embedding = vectors[0]

    # Build metadata (ChromaDB metadata values must be str, int, float, or bool).
    git_ref = _sec_git_ref()
    meta: dict[str, Any] = {
        "file": file,
        "tag": tag,
        "version": new_version,
        "updated": _now_utc_iso(),
        "by": _git_user(),
        "source_hash": new_hash,
        "doc_type": doc_type,
        "model": model if model is not None else "",
        "git_ref": git_ref if git_ref is not None else "",
        "confidence": float(confidence) if confidence is not None else -1.0,
        "converged": bool(converged) if converged is not None else False,
    }

    collection.upsert(
        ids=[doc_id],
        documents=[content],
        embeddings=[embedding],
        metadatas=[meta],
    )
    return True


def section_get_chroma(file: str, tag: str) -> tuple[str, dict[str, Any]] | None:
    """Read a section from ChromaDB. Return (content, metadata_dict) or None."""
    doc_id = _doc_id(file, tag)
    collection = _descriptions_col()

    result = collection.get(ids=[doc_id], include=["documents", "metadatas"])
    if not result or not result["ids"]:
        return None

    content = result["documents"][0]
    metadata = result["metadatas"][0]
    return (content, metadata)


def section_query_chroma(
    *,
    where: dict[str, Any] | None = None,
    limit: int = 50,
) -> list[tuple[str, str, dict[str, Any]]]:
    """Filter ChromaDB by metadata. Return [(doc_id, content, metadata), ...].

    'where' is passed through to ChromaDB's get(where=...) — operators like
    {'doc_type': 'function_description', 'file': '/path/to/file.py'}.
    Returns up to `limit` rows.
    """
    collection = _descriptions_col()

    kwargs: dict[str, Any] = {
        "include": ["documents", "metadatas"],
        "limit": limit,
    }
    if where is not None:
        kwargs["where"] = where

    result = collection.get(**kwargs)
    if not result or not result["ids"]:
        return []

    return [
        (doc_id, doc, meta)
        for doc_id, doc, meta in zip(
            result["ids"], result["documents"], result["metadatas"]
        )
    ]


