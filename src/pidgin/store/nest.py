def _build_function_metadata(
    *,
    file: str,
    name: str,
    line_start: int,
    line_end: int,
    description: str,
    language: str,
    module: str,
    visibility: str,
    natural_length: int,
    git_ref: str,
    signature_json: str | None = None,
    decorators_str: str | None = None,
) -> dict[str, Any]:
    """Assemble the metadata dict written into both function collections.

    Chroma metadata values must be str | int | float | bool.

    M12: Two optional fields added for full AST metadata:
      signature_json  — JSON-serialised FunctionSignature dict (str), or ""
                        when not provided (sentinel for pre-M12 records).
      decorators_str  — comma-joined decorator names (str), or "" when absent.
    Both default to "" so pre-M12 records are backward-compatible (Chroma
    is permissive — older rows simply lack these keys until re-indexed).
    """
    import json as _json
    meta: dict[str, Any] = {
        "file": file,
        "line_start": line_start,
        "line_end": line_end,
        "name": name,
        "language": language,
        "module": module,
        "visibility": visibility,
        "description": description,
        "natural_length": natural_length,
        "git_ref": git_ref,
        "signature_json": signature_json if signature_json is not None else "",
        "decorators_str": decorators_str if decorators_str is not None else "",
    }
    return meta


