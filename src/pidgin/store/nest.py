def delete_function(fid: str) -> None:
    """Remove the entry from both function collections.

    Used when a function is deleted from source. Idempotent — deleting a
    non-existent id is a Chroma no-op.
    """
    bodies, descriptions = _vec_collections()
    bodies.delete(ids=[fid])
    descriptions.delete(ids=[fid])


def reset_all() -> None:
    """Drop both function collections and recreate them. Test/dev use only.

    Does NOT touch the sections store's 'descriptions' collection — safe to
    call without affecting sections data.
    """
    global _vec_client_cache
    client = _vec_client()
    for name in (_COLLECTION_BODIES, _COLLECTION_FUNC_DESCRIPTIONS):
        try:
            client.delete_collection(name=name)
        except Exception:
            pass
    # Recreate empties so the next caller hits warm collections.
    _vec_collections()


