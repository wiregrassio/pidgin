def _format_hits(result: dict) -> list[dict]:
    """Convert a Chroma query() result into the public hit shape.

    Public hit shape: {id, distance, file, line_start, line_end, name, description}.
    Chroma's query() returns each field as a list-of-lists (one inner list per
    query string). We always issue single-query searches, so we collapse [0].
    """
    if not result or not result.get("ids") or not result["ids"][0]:
        return []

    ids = result["ids"][0]
    distances = (result.get("distances") or [[None] * len(ids)])[0]
    metadatas = (result.get("metadatas") or [[{}] * len(ids)])[0]

    hits: list[dict] = []
    for i, fid in enumerate(ids):
        meta = metadatas[i] or {}
        hits.append({
            "id": fid,
            "distance": distances[i],
            "file": meta.get("file"),
            "line_start": meta.get("line_start"),
            "line_end": meta.get("line_end"),
            "name": meta.get("name"),
            "description": meta.get("description"),
        })
    return hits


async def find_by_body(query: str, k: int = 5) -> list[dict]:
    """Search function_bodies. "Find functions that handle X."

    Embeds the query string via embed_for_store, runs a vector search against
    function_bodies, and returns the top k hits as
    {id, distance, file, line_start, line_end, name, description}.
    """
    vectors = await api.embed_for_store(query)
    query_vec = vectors[0]

    bodies, _ = _vec_collections()
    result = bodies.query(
        query_embeddings=[query_vec],
        n_results=k,
        include=["metadatas", "distances"],
    )
    return _format_hits(result)


async def find_similar_to_description(description: str, k: int = 5) -> list[dict]:
    """Search function_descriptions. "Find functions similar to this one."

    Embeds the description via embed_for_store, runs a vector search against
    function_descriptions, and returns the top k hits in the same shape
    as find_by_body.
    """
    vectors = await api.embed_for_store(description)
    query_vec = vectors[0]

    _, descriptions = _vec_collections()
    result = descriptions.query(
        query_embeddings=[query_vec],
        n_results=k,
        include=["metadatas", "distances"],
    )
    return _format_hits(result)


