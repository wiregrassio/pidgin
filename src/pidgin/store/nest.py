def _sec_client() -> chromadb.api.ClientAPI:
    """Open or create the persistent ChromaDB client at store_path() (sections side)."""
    path = store_path()
    path.mkdir(parents=True, exist_ok=True)
    settings = chromadb.Settings(
        anonymized_telemetry=False,
        allow_reset=True,
    )
    return chromadb.PersistentClient(path=str(path), settings=settings)


def _descriptions_col() -> chromadb.Collection:
    """Get-or-create the 'descriptions' collection for the sections store.

    embedding_function=None — we supply embeddings explicitly via api.embed_text.
    """
    client = _sec_client()
    return client.get_or_create_collection(
        name=_COLLECTION_DESCRIPTIONS,
        embedding_function=None,
        metadata={"hnsw:space": "cosine"},
    )


# ---------------------------------------------------------------------------
# Vector-store client and collection helpers
# ---------------------------------------------------------------------------

def _vec_client() -> chromadb.api.ClientAPI:
    """Open (or reuse) the persistent ChromaDB client at store_path() (vectors side).

    Cached at module level — Chroma's PersistentClient is intended to be a
    long-lived handle within a process.
    """
    global _vec_client_cache
    if _vec_client_cache is not None:
        return _vec_client_cache
    path = store_path()
    path.mkdir(parents=True, exist_ok=True)
    settings = chromadb.Settings(
        anonymized_telemetry=False,
        allow_reset=True,
    )
    _vec_client_cache = chromadb.PersistentClient(path=str(path), settings=settings)
    return _vec_client_cache


def _vec_collections() -> tuple[chromadb.Collection, chromadb.Collection]:
    """Return (function_bodies, function_descriptions) collections, creating if needed.

    Both collections configured with embedding_function=None — we always supply
    pre-computed vectors via embed_for_store and never let Chroma's default embedder run.
    """
    client = _vec_client()
    bodies = client.get_or_create_collection(
        name=_COLLECTION_BODIES,
        embedding_function=None,
        metadata={"hnsw:space": "cosine"},
    )
    descriptions = client.get_or_create_collection(
        name=_COLLECTION_FUNC_DESCRIPTIONS,
        embedding_function=None,
        metadata={"hnsw:space": "cosine"},
    )
    return (bodies, descriptions)


